#!/usr/bin/env bash
# Wraps the artifact body (src/roadmap-studio.html) into a standalone
# document you can open straight from disk, and that Vercel serves as-is:
# index.html.
#
# The Artifact platform supplies the doctype/head/reset at publish time, so
# the source file carries only the page body. This adds the same skeleton.
# Pure bash + awk on purpose: it has to run in any CI image.

set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
src="$here/src/roadmap-studio.html"
out="$here/index.html"

[ -f "$src" ] || { echo "missing $src" >&2; exit 1; }

cat > "$out" <<'HEAD'
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="description" content="Quartermap builds the two quarterly roadmap slides, product and design, by painting phases on the sprint grid.">
<meta name="color-scheme" content="light dark">
<meta name="theme-color" content="#101012">
<link rel="icon" href="favicon.svg" type="image/svg+xml">
<link rel="icon" href="favicon-32.png" type="image/png" sizes="32x32">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<style>
  :root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}
  body{margin:0;font:14px system-ui,sans-serif;background:#faf9f7}
  img{max-width:100%}
  [hidden]{display:none!important}
</style>
HEAD

# The body starts at the first top-level <div class="app">: close the head and
# open the body right before it.
awk '
  !opened && /^<div class="app">/ { print "</head>"; print "<body>"; opened = 1 }
  { print }
  END { if (!opened) { print "awk: body marker not found" > "/dev/stderr"; exit 1 } }
' "$src" >> "$out"

printf '</body>\n</html>\n' >> "$out"

echo "built $out ($(wc -c < "$out" | tr -d ' ') bytes)"

# The roadmap rules are shared with the Claude connector (api/mcp.js): the
# <script id="qm-model"> block of the page is copied word for word into
# lib/model.cjs, so the editor and the connector can never disagree.
model="$here/lib/model.cjs"
mkdir -p "$here/lib"
{
  echo "// Generated by build.sh from the <script id=\"qm-model\"> block of"
  echo "// src/roadmap-studio.html. Do not edit: change the page and build again."
  awk '
    /^<script id="qm-model">$/ { inside = 1; found = 1; next }
    inside && /^<\/script>$/ { inside = 0; next }
    inside { print }
    END { if (!found) { print "awk: model block not found" > "/dev/stderr"; exit 1 } }
  ' "$src"
} > "$model"
echo "built $model ($(wc -c < "$model" | tr -d ' ') bytes)"

# The page where someone approves a connection to Claude (OAuth consent). It
# is a document of its own, copied as it is: Vercel serves it at /oauth/consent.
consent="$here/oauth/consent.html"
mkdir -p "$here/oauth"
cp "$here/src/consent.html" "$consent"
echo "built $consent ($(wc -c < "$consent" | tr -d ' ') bytes)"
